# ---------------- Utility Functions ----------------
def save_plotly_as_image(fig):
    try:
        tmpfile = tempfile.NamedTemporaryFile(delete=False, suffix=".png")
        fig.write_image(tmpfile.name, format="png", engine="kaleido")
        return tmpfile.name
    except Exception as e:
        st.warning(f"❌ Chart export failed: {e}. Chart will be omitted from PDF.")
        return None

def get_alerts(df, role):
    alerts = []
    if not df.empty:
        # High frequency crime alert
        top_type = df['crime_type'].value_counts().idxmax()
        top_count = df['crime_type'].value_counts().max()
        if top_count > 50:
            alerts.append(f"🚨 High number of {top_type} incidents detected: {top_count} cases.")

        # Spike in last 7 days
        last_7d = df[df['date'] >= pd.Timestamp.now() - pd.Timedelta(days=7)]
        if len(last_7d) > 0 and (len(last_7d) / len(df)) > 0.25:
            alerts.append(f"📊 {len(last_7d)} incidents reported in the last 7 days. Monitor trends closely.")

    # Role-specific alert
    if role == "law_enforcement":
        alerts.append("⚠️ System maintenance scheduled for Sunday midnight (01:00–03:00).")

    return alerts

def generate_pdf_report(df, username, chart_paths, alerts):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", "B", 16)
    pdf.cell(0, 10, "Crime Report Summary", ln=1, align="C")
    pdf.set_font("Arial", size=12)
    pdf.ln(2)
    pdf.cell(0, 8, f"Generated by: {username}", ln=1)
    pdf.cell(0, 8, f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ln=1)
    pdf.ln(5)

    # Alerts
    if alerts:
        pdf.set_font("Arial", "B", 14)
        pdf.cell(0, 8, "Alerts & Notifications:", ln=1)
        pdf.set_font("Arial", size=12)
        for alert in alerts:
            pdf.multi_cell(0, 6, f"- {alert}")
        pdf.ln(5)

    # Summary stats
    pdf.set_font("Arial", "B", 14)
    pdf.cell(0, 8, "Crime Type Counts:", ln=1)
    pdf.set_font("Arial", size=12)
    summary = df["crime_type"].value_counts().reset_index()
    summary.columns = ["crime_type", "count"]
    for _, row in summary.iterrows():
        pdf.cell(0, 6, f"{row['crime_type']}: {row['count']}", ln=1)
    pdf.ln(5)

    # Add charts
    for path in chart_paths:
        if path and os.path.exists(path):
            try:
                pdf.image(path, w=180)
                pdf.ln(5)
            except Exception:
                pass

    pdf_bytes = io.BytesIO()
    pdf_output = pdf.output(dest="S").encode("latin-1")
    pdf_bytes.write(pdf_output)
    pdf_bytes.seek(0)
    return pdf_bytes

